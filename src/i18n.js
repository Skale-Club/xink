let language = 'en';

function setLanguage(code) {
  language = I18N[code] ? code : 'en';
  document.documentElement.lang = language;
}

function t(key, vars = {}) {
  const text = I18N[language][key] ?? I18N.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}
